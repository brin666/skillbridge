_PROTECTED_PRODUCT_TERMS = ("After Effects", "Three.js")


class RuleSummaryProvider:
    """Generates summaries without AI."""

    def generate(self, description: str, content: str, target_language: str) -> str:
        description = (description or "").strip()
        if target_language == "en-US":
            return self._en_summary(description, content)
        return self._zh_summary(description, content)

    def _en_summary(self, description: str, content: str) -> str:
        if description:
            return self._clean(description)
        first = self._first_meaningful_line(content)
        return self._clean(first) if first else ""

    def _zh_summary(self, description: str, content: str) -> str:
        if not description:
            first = self._first_meaningful_line(content)
            if first:
                return self._clean(first)
            return ""
        if self._contains_cjk(description) and not self._contains_ascii_letters(description):
            return self._clean(description)

        text = description
        for phrase, zh in sorted(_PHRASES.items(), key=lambda item: len(item[0]), reverse=True):
            text = re.sub(re.escape(phrase), zh, text, flags=re.IGNORECASE)
        protected_products: list[tuple[str, str]] = []
        for index, product in enumerate(_PROTECTED_PRODUCT_TERMS):
            token = f"\ue000{index}\ue001"
            text = re.sub(re.escape(product), token, text, flags=re.IGNORECASE)
            protected_products.append((token, product))
        for english, chinese in (("user", "用户"), ("task", "任务"), ("agent", "Agent"), ("skill", "Skill")):
            text = re.sub(rf"\b{english}['’]s\b", f"{chinese}的", text, flags=re.IGNORECASE)
        # Descriptions frequently use an English subject prefix; omit it in the
        # Chinese sentence instead of producing awkward output like “技能编辑…”.
        text = re.sub(r"(?i)^this skill\s+", "", text)
        for en, zh in _TERMS.items():
            text = re.sub(rf"\b{re.escape(en)}\b", zh, text, flags=re.IGNORECASE)
        for token, product in protected_products:
            text = text.replace(token, product)
        text = re.sub(r"\b(?:the|a|an|and|or|of|to|in|on|at|by|as|that|which|this|these|those|can|will|you|your|my|do|does)\b", " ", text, flags=re.IGNORECASE)
        text = re.sub(r"\b(?:is|are|be)\b", "", text, flags=re.IGNORECASE)
        text = re.sub(r"\s+", " ", text).strip()
        text = re.sub(r"(?<=[\u4e00-\u9fff])\s+(?=[\u4e00-\u9fff])", "", text)
        text = re.sub(r"(?<=[\u4e00-\u9fff])\s+([,;:])\s*", r"\1", text)
        text = re.sub(r"(?<=[\u4e00-\u9fff]):\s*", "：", text)
        text = re.sub(r"(?<=[\u4e00-\u9fff]),\s*", "，", text)
        text = re.sub(r"\s+([，。；、])", r"\1", text)
        text = text.strip(".,;:。；， ")
        if self._translation_is_fragmentary(text):
            # Prefer a complete source sentence over a misleading half-translation.
            # The feature is still known; this fallback is not the UI's “Unknown”.
            return self._clean(description)
        # Preserve unknown product/technical terms rather than inventing a generic
        # capability; known actions and common words are translated above.
        if text.startswith(("适用于", "用于", "帮助", "支持", "提供", "将", "用户", "主 Agent")) or re.match(
            r"^(?:只读|避免|管理|使用|生成|创建|编辑|读取|编写|构建|设计|转换|检查|审查|分析|搜索|提取|执行|运行|停止|同步|连接|配置|导入|更换|停用|产出|自动|核对|可|根据|为|在|从|通过|比较|让)",
            text,
        ) or re.match(r"^(?:After Effects\s+(?:是|可|支持|用于)|[A-Z][A-Za-z0-9+#.-]*\s+(?:可以|可|支持))", text):
            return text
        return f"用于{text}。"

    @staticmethod
    def _translation_is_fragmentary(text: str) -> bool:
        words = re.findall(r"\b[A-Za-z][A-Za-z0-9+#.-]*\b", text)
        if not words:
            return False
        untranslated = [
            word
            for word in words
            if not word.isupper()
            and not re.search(r"[a-z][A-Z]", word)
            and word.casefold() not in _PRESERVED_ENGLISH_TERMS
        ]
        return len(untranslated) >= 2 and len(untranslated) / len(words) >= 0.35

    @staticmethod
    def _clean(text: str) -> str:
        text = re.sub(r"\s+", " ", text).strip()
        return text.rstrip(".")

    @staticmethod
    def _first_meaningful_line(content: str) -> str:
        for line in content.splitlines()[:20]:
            stripped = line.strip()
            if not stripped or stripped.startswith(("#", "```", "~~~")):
                continue
            clean = re.sub(r"^(?:[-*+]\s+|\d+[.)]\s+)", "", stripped)
            if clean and not re.match(
                r"(?i)^(?:author(?:\s*/\s*author)?|作者(?:\s*/\s*author)?|英文名|english name|来源识别|source identification)\s*[:：]",
                clean,
            ):
                return clean
        return ""

    @staticmethod
    def _contains_cjk(text: str) -> bool:
        return any("\u4e00" <= ch <= "\u9fff" for ch in text)

    @staticmethod
    def _contains_ascii_letters(text: str) -> bool:
        return bool(re.search(r"[a-z]", text))
